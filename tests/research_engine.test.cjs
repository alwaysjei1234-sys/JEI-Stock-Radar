const assert=require('node:assert/strict');
const {research,scenario,performance}=require('../remote/research_engine.js');
const empty=research({symbol:'TEST',epsTTM:0,evidence:[{text:'傳聞',status:'rumor'}]});
assert.equal(empty.coverage.verified,1,'zero is a valid reported metric');
assert.equal(empty.metrics.revenueYoY,null,'missing is not zero');
assert.equal(empty.confirmedEvidence,0);
assert.equal(empty.peerComparisonReady,false);
assert.equal(scenario({price:110,support:90,resistance:100}).state,'strength');
assert.equal(scenario({price:80,support:90,resistance:100}).state,'breakdown');
assert.equal(scenario({price:95,support:90,resistance:100}).state,'range');
assert.equal(scenario({price:95,support:100,resistance:90}).state,'insufficient');
const events=[{id:'one',symbol:'TEST',date:'2026-10-01',entryPrice:100,roundTripCostPct:0.5}];
const quotes={TEST:[{date:'2026-10-01',close:100},{date:'2026-10-02',close:110},{date:'2026-10-05',close:90}]};
const results=performance(events,quotes,[1,2,3]);
assert.equal(results[0].state,'completed');
assert.equal(results[0].netPct,9.5);
assert.equal(results[1].netPct,-10.5);
assert.equal(results[2].state,'pending');
assert.equal(results[2].netPct,null);
