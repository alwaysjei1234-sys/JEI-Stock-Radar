"""Deterministic, fail-closed gate for independent AI strategy proposals.

Input is a JSON bundle generated by separately configured model runners.
This tool does not call any model, place orders, or deploy a strategy.
"""
import argparse
import json
import pathlib
import sys

MIN_TRADES = 100
MIN_REGIMES = 3
MIN_WIN_RATE = 0.80

def evaluate(bundle):
    reasons = []
    proposals = bundle.get("proposals", [])
    roles = {p.get("role") for p in proposals if isinstance(p, dict)}
    models = {p.get("model_id") for p in proposals if isinstance(p, dict) and p.get("model_id")}
    if not {"researcher", "critic"}.issubset(roles) or len(models) < 2:
        reasons.append("need_independent_researcher_and_critic_models")
    candidate = bundle.get("candidate", {})
    baseline = bundle.get("baseline", {})
    if not candidate.get("strategy_id") or not candidate.get("code_commit"):
        reasons.append("missing_candidate_identity")
    if not bundle.get("data_provenance") or not bundle.get("backtest_version"):
        reasons.append("missing_reproducibility_evidence")
    if bundle.get("lookahead_detected") is not False:
        reasons.append("lookahead_not_ruled_out")
    if bundle.get("overlap_removed") is not True:
        reasons.append("overlapping_trades_not_resolved")
    if bundle.get("costs_included") is not True:
        reasons.append("transaction_costs_not_verified")
    for label, metrics in (("candidate", candidate), ("baseline", baseline)):
        for key in ("oos_trades", "market_regimes", "net_expectancy", "win_rate", "max_drawdown"):
            if type(metrics.get(key)) not in (int, float):
                reasons.append(label + "_missing_" + key)
    if reasons:
        return {"decision": "REJECT", "reasons": reasons, "auto_deploy": False}
    if candidate["oos_trades"] < MIN_TRADES:
        reasons.append("insufficient_out_of_sample_trades")
    if candidate["market_regimes"] < MIN_REGIMES:
        reasons.append("insufficient_market_regimes")
    if candidate["win_rate"] < MIN_WIN_RATE:
        reasons.append("win_rate_below_80_percent")
    if candidate["net_expectancy"] <= 0:
        reasons.append("nonpositive_net_expectancy")
    if candidate["net_expectancy"] <= baseline["net_expectancy"]:
        reasons.append("no_expectancy_improvement")
    if candidate["max_drawdown"] > baseline["max_drawdown"]:
        reasons.append("drawdown_worse_than_baseline")
    return {"decision": "REVIEW" if not reasons else "REJECT",
            "reasons": reasons, "auto_deploy": False,
            "note": "REVIEW means eligible for human-reviewed PR, never automatic production rollout"}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", default="evolution-output/evaluation.json")
    args = parser.parse_args()
    try:
        bundle = json.loads(pathlib.Path(args.input).read_text(encoding="utf-8"))
        result = evaluate(bundle)
    except (OSError, ValueError, TypeError) as exc:
        result = {"decision": "REJECT", "reasons": ["invalid_input: " + str(exc)], "auto_deploy": False}
    path = pathlib.Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(result, ensure_ascii=False))
    return 0 if result["decision"] == "REVIEW" else 1

if __name__ == "__main__":
    sys.exit(main())
